-- Optional OAuth registration for the local Codex MCP client.
CREATE SECURITY INTEGRATION IF NOT EXISTS LAUNCH_MYSTERY_CODEX_OAUTH
    TYPE = OAUTH
    ENABLED = TRUE
    OAUTH_CLIENT = CUSTOM
    OAUTH_CLIENT_TYPE = 'CONFIDENTIAL'
    OAUTH_REDIRECT_URI = 'http://127.0.0.1:8765/callback'
    OAUTH_ALLOW_NON_TLS_REDIRECT_URI = TRUE
    OAUTH_USE_SECONDARY_ROLES = NONE
    ALLOWED_ROLES_LIST = ('LAUNCH_MYSTERY_MCP_READER');

ALTER SCHEMA LAUNCH_MYSTERY.DEMO
    SET OAUTH_SCOPES_SUPPORTED = 'session:role:LAUNCH_MYSTERY_MCP_READER';

SELECT 'https://' ||
       LOWER(REPLACE(CURRENT_ORGANIZATION_NAME() || '-' ||
                     CURRENT_ACCOUNT_NAME(), '_', '-')) ||
       '.snowflakecomputing.com/api/v2/databases/LAUNCH_MYSTERY' ||
       '/schemas/DEMO/mcp-servers/INCIDENT_MCP' AS MCP_SERVER_URL;
