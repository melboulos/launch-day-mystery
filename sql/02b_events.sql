USE SCHEMA LAUNCH_MYSTERY.DEMO;
USE WAREHOUSE LAUNCH_MYSTERY_WH;

-- The eight scenario rows set the totals. Generate the underlying sessions
-- deterministically so the same shoppers and funnel counts appear on each deploy.
CREATE OR REPLACE TRANSIENT TABLE SHOPPER_EVENTS AS
WITH slots AS (
    SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) AS slot
    FROM TABLE(GENERATOR(ROWCOUNT => 10000))
), sessions AS (
    SELECT s.WINDOW_START_UTC, s.RELEASE_PHASE, s.PLATFORM, s.COHORT,
           s.CHECKOUT_STARTS, s.ORDERS, n.slot,
           SHA2(CONCAT_WS('|', TO_CHAR(s.WINDOW_START_UTC, 'YYYY-MM-DD HH24:MI:SS'),
                          s.PLATFORM, s.COHORT, TO_VARCHAR(n.slot))) AS SESSION_ID,
           DATEADD(second, MOD(n.slot * 137, 3480), s.WINDOW_START_UTC) AS SESSION_START_UTC
    FROM CHECKOUT_HOURLY AS s
    JOIN slots AS n ON n.slot <= s.STOREFRONT_SESSIONS
), events AS (
    SELECT SESSION_ID, WINDOW_START_UTC, RELEASE_PHASE, PLATFORM, COHORT,
           SESSION_START_UTC AS EVENT_AT_UTC, 'storefront_session' AS EVENT_NAME
    FROM sessions
    UNION ALL
    SELECT SESSION_ID, WINDOW_START_UTC, RELEASE_PHASE, PLATFORM, COHORT,
           DATEADD(second, 30, SESSION_START_UTC), 'checkout_started'
    FROM sessions WHERE slot <= CHECKOUT_STARTS
    UNION ALL
    SELECT SESSION_ID, WINDOW_START_UTC, RELEASE_PHASE, PLATFORM, COHORT,
           DATEADD(second, 60, SESSION_START_UTC), 'order_placed'
    FROM sessions WHERE slot <= ORDERS
    UNION ALL
    SELECT SESSION_ID, WINDOW_START_UTC, RELEASE_PHASE, PLATFORM, COHORT,
           DATEADD(second, 60, SESSION_START_UTC), 'address_validation_timeout'
    FROM sessions
    WHERE slot > ORDERS AND slot <= CHECKOUT_STARTS
      AND slot <= ORDERS + CASE
          WHEN PLATFORM = 'iOS' AND COHORT = 'Rollout' AND RELEASE_PHASE = 'After' THEN 120
          ELSE 8
      END
)
SELECT * FROM events;

CREATE OR REPLACE VIEW CHECKOUT_EVENT_FUNNEL AS
SELECT WINDOW_START_UTC, RELEASE_PHASE, PLATFORM, COHORT,
       COUNT(CASE WHEN EVENT_NAME = 'storefront_session' THEN 1 END) AS STOREFRONT_SESSIONS,
       COUNT(CASE WHEN EVENT_NAME = 'checkout_started' THEN 1 END) AS CHECKOUT_STARTS,
       COUNT(CASE WHEN EVENT_NAME = 'order_placed' THEN 1 END) AS ORDERS,
       COUNT(CASE WHEN EVENT_NAME = 'address_validation_timeout' THEN 1 END) AS ADDRESS_TIMEOUTS
FROM SHOPPER_EVENTS
GROUP BY WINDOW_START_UTC, RELEASE_PHASE, PLATFORM, COHORT;
