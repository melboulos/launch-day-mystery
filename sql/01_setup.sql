-- Run with a role authorized to create these dedicated demo objects.
CREATE WAREHOUSE IF NOT EXISTS LAUNCH_MYSTERY_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS LAUNCH_MYSTERY;
CREATE SCHEMA IF NOT EXISTS LAUNCH_MYSTERY.DEMO;
USE SCHEMA LAUNCH_MYSTERY.DEMO;
USE WAREHOUSE LAUNCH_MYSTERY_WH;

CREATE STAGE IF NOT EXISTS APP_FILES;

CREATE TABLE IF NOT EXISTS CHECKOUT_HOURLY (
  WINDOW_START_UTC TIMESTAMP_NTZ NOT NULL,
  RELEASE_PHASE VARCHAR NOT NULL,
  PLATFORM VARCHAR NOT NULL,
  COHORT VARCHAR NOT NULL,
  STOREFRONT_SESSIONS INTEGER NOT NULL,
  CHECKOUT_STARTS INTEGER NOT NULL,
  ORDERS INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS INCIDENT_NOTES (
  DOC_ID VARCHAR NOT NULL,
  TITLE VARCHAR NOT NULL,
  BODY VARCHAR NOT NULL
);
